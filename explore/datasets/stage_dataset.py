import torch
from torch.utils.data import Dataset


class StaGEDataset(Dataset):
    """
    Torch Dataset that stores (state, action, next_state, reward, done)
    transitions generated by StaGE tree rollouts.

    Data is kept as torch tensors in memory and grown incrementally via
    `add_multiple`. Can be pickled/unpickled directly since it holds only
    tensors and plain Python state.
    """

    def __init__(self):
        self.states = torch.empty((0,), dtype=torch.float32)
        self.actions = torch.empty((0,), dtype=torch.float32)
        self.next_states = torch.empty((0,), dtype=torch.float32)
        self.rewards = torch.empty((0,), dtype=torch.float32)
        self.dones = torch.empty((0,), dtype=torch.float32)

    def add_multiple(self, states, actions, next_states, rewards, dones):
        states = torch.as_tensor(states, dtype=torch.float32)
        actions = torch.as_tensor(actions, dtype=torch.float32)
        next_states = torch.as_tensor(next_states, dtype=torch.float32)
        rewards = torch.as_tensor(rewards, dtype=torch.float32).reshape(-1, 1)
        dones = torch.as_tensor(dones, dtype=torch.float32).reshape(-1, 1)

        if len(self.states) == 0:
            self.states = states
            self.actions = actions
            self.next_states = next_states
            self.rewards = rewards
            self.dones = dones
        else:
            self.states = torch.cat([self.states, states], dim=0)
            self.actions = torch.cat([self.actions, actions], dim=0)
            self.next_states = torch.cat([self.next_states, next_states], dim=0)
            self.rewards = torch.cat([self.rewards, rewards], dim=0)
            self.dones = torch.cat([self.dones, dones], dim=0)

    def __len__(self):
        return len(self.states)

    def __getitem__(self, idx):
        return (
            self.states[idx],
            self.actions[idx],
            self.next_states[idx],
            self.rewards[idx],
            self.dones[idx],
        )

    def state_dict(self):
        """Plain tensor dict, safe to torch.save/load across projects."""
        return {
            "states": self.states,
            "actions": self.actions,
            "next_states": self.next_states,
            "rewards": self.rewards,
            "dones": self.dones,
        }

    def load_state_dict(self, state_dict):
        self.states = state_dict["states"]
        self.actions = state_dict["actions"]
        self.next_states = state_dict["next_states"]
        self.rewards = state_dict["rewards"]
        self.dones = state_dict["dones"]
        return self

    @classmethod
    def from_state_dict(cls, state_dict):
        return cls().load_state_dict(state_dict)
